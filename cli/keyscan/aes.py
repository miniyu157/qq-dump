def _xtime(a: int) -> int:
    """GF(2^8) 乘 2。"""
    a <<= 1
    return (a ^ 0x1B) & 0xFF if a & 0x100 else a


def _mul(a: int, b: int) -> int:
    """GF(2^8) 乘法, 仅用于在导入时生成查表。"""
    result = 0
    for _ in range(8):
        if b & 1:
            result ^= a
        b >>= 1
        a = _xtime(a)
    return result


def _ror(word: int, bits: int) -> int:
    return ((word >> bits) | (word << (32 - bits))) & 0xFFFFFFFF


# 解密 T 表: 把 InvSubBytes 与 InvMixColumns 合并为每字节一次查表, 每轮每列 4 次查表 + 异或。
# 纯 Python 逐字节运算解一页约 300 ms, 查表后约 20 倍快; 正确性由 FIPS-197 与 SP 800-38A 向量测试保证
_TD0 = tuple((_mul(s, 14) << 24) | (_mul(s, 9) << 16) | (_mul(s, 13) << 8) | _mul(s, 11) for s in _INV_SBOX)
_TD1 = tuple(_ror(word, 8) for word in _TD0)
_TD2 = tuple(_ror(word, 16) for word in _TD0)
_TD3 = tuple(_ror(word, 24) for word in _TD0)
# InvMixColumns 单独作用于一个字 (用于把加密轮密钥转换为解密轮密钥)
_IMC0 = tuple((_mul(b, 14) << 24) | (_mul(b, 9) << 16) | (_mul(b, 13) << 8) | _mul(b, 11) for b in range(256))
_IMC1 = tuple(_ror(word, 8) for word in _IMC0)
_IMC2 = tuple(_ror(word, 16) for word in _IMC0)
_IMC3 = tuple(_ror(word, 24) for word in _IMC0)


def _inv_mix_word(word: int) -> int:
    return _IMC0[word >> 24] ^ _IMC1[(word >> 16) & 0xFF] ^ _IMC2[(word >> 8) & 0xFF] ^ _IMC3[word & 0xFF]


def _expand_key(key: bytes) -> list[tuple[int, int, int, int]]:
    """AES-256 密钥扩展, 返回按解密顺序排列的 15 组轮密钥, 每组为 4 个大端 32 位字。

    中间 13 轮的轮密钥预先经 InvMixColumns 变换 (等价逆密码结构), 使解密轮可直接用 T 表。
    """
    nk = 8  # 256 位 = 8 个字
    total_words = _BLOCK * (_ROUNDS + 1) // 4
    words = [int.from_bytes(key[4 * i:4 * i + 4], "big") for i in range(nk)]
    for i in range(nk, total_words):
        temp = words[i - 1]
        if i % nk == 0:
            temp = ((temp << 8) | (temp >> 24)) & 0xFFFFFFFF  # RotWord
            temp = (_SBOX[temp >> 24] << 24) | (_SBOX[(temp >> 16) & 0xFF] << 16) | (_SBOX[(temp >> 8) & 0xFF] << 8) | _SBOX[temp & 0xFF]
            temp ^= _RCON[i // nk - 1] << 24
        elif i % nk == 4:
            temp = (_SBOX[temp >> 24] << 24) | (_SBOX[(temp >> 16) & 0xFF] << 16) | (_SBOX[(temp >> 8) & 0xFF] << 8) | _SBOX[temp & 0xFF]
        words.append(words[i - nk] ^ temp)
    rounds = [tuple(words[4 * r:4 * r + 4]) for r in range(_ROUNDS + 1)]
    decrypt = [rounds[_ROUNDS]]
    decrypt += [tuple(_inv_mix_word(word) for word in rounds[r]) for r in range(_ROUNDS - 1, 0, -1)]
    decrypt.append(rounds[0])
    return decrypt


def _decrypt_block(block: bytes, round_keys: list[tuple[int, int, int, int]]) -> bytes:
    """解一个 16 字节块 (等价逆密码, 中间轮用 T 表)。"""
    k = round_keys[0]
    s0 = int.from_bytes(block[0:4], "big") ^ k[0]
    s1 = int.from_bytes(block[4:8], "big") ^ k[1]
    s2 = int.from_bytes(block[8:12], "big") ^ k[2]
    s3 = int.from_bytes(block[12:16], "big") ^ k[3]
    td0, td1, td2, td3 = _TD0, _TD1, _TD2, _TD3
    for k in round_keys[1:_ROUNDS]:
        t0 = td0[s0 >> 24] ^ td1[(s3 >> 16) & 0xFF] ^ td2[(s2 >> 8) & 0xFF] ^ td3[s1 & 0xFF] ^ k[0]
        t1 = td0[s1 >> 24] ^ td1[(s0 >> 16) & 0xFF] ^ td2[(s3 >> 8) & 0xFF] ^ td3[s2 & 0xFF] ^ k[1]
        t2 = td0[s2 >> 24] ^ td1[(s1 >> 16) & 0xFF] ^ td2[(s0 >> 8) & 0xFF] ^ td3[s3 & 0xFF] ^ k[2]
        t3 = td0[s3 >> 24] ^ td1[(s2 >> 16) & 0xFF] ^ td2[(s1 >> 8) & 0xFF] ^ td3[s0 & 0xFF] ^ k[3]
        s0, s1, s2, s3 = t0, t1, t2, t3
    # 末轮只有 InvShiftRows、InvSubBytes 与 AddRoundKey, 没有 InvMixColumns
    k = round_keys[_ROUNDS]
    inv = _INV_SBOX
    out = bytearray(16)
    for col, (a, b, c, d) in enumerate(((s0, s3, s2, s1), (s1, s0, s3, s2), (s2, s1, s0, s3), (s3, s2, s1, s0))):
        word = (inv[a >> 24] << 24) | (inv[(b >> 16) & 0xFF] << 16) | (inv[(c >> 8) & 0xFF] << 8) | inv[d & 0xFF]
        out[4 * col:4 * col + 4] = (word ^ k[col]).to_bytes(4, "big")
    return bytes(out)


def aes256_cbc_decrypt(key: bytes, iv: bytes, ciphertext: bytes) -> bytes:
    """AES-256-CBC 解密; key 须 32 字节, iv 16 字节, ciphertext 为 16 的整数倍, 不去 padding。"""
    if len(key) != 32:
        raise ValueError("AES-256 密钥须为 32 字节")
    if len(iv) != _BLOCK:
        raise ValueError("IV 须为 16 字节")
    if len(ciphertext) % _BLOCK != 0:
        raise ValueError("密文长度须为 16 的整数倍")
    round_keys = _expand_key(key)
    out = bytearray()
    prev = int.from_bytes(iv, "big")
    for off in range(0, len(ciphertext), _BLOCK):
        block = ciphertext[off:off + _BLOCK]
        plain = int.from_bytes(_decrypt_block(block, round_keys), "big") ^ prev
        out += plain.to_bytes(_BLOCK, "big")
        prev = int.from_bytes(block, "big")
    return bytes(out)
